// Клавиатура для раздела: ссылки раздела + кнопка возврата в меню.
// Возвращает массив рядов вида {text, url} или {text, data}.
export function keyboardFor(sectionId) {
  if (sectionId === "start") {
    return [
      ...MENU.map((row) => row.map((b) => ({ text: b.text, data: b.id }))),
      [{ text: "Канал в MAX", url: LINKS.channel }, { text: "Сайт проекта", url: LINKS.site }],
    ];
  }
  const section = SECTIONS[sectionId];
  const rows = [...(section.buttons || [])];
  const hasChannel = rows.some((row) => row.some((b) => b.url === LINKS.channel));
  if (!hasChannel) rows.push([{ text: "Читать канал в MAX", url: LINKS.channel }]);
  return [...rows, [{ text: "« В меню", data: "start" }]];
}
