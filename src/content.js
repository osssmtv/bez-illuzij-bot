// Клавиатура для раздела: ссылки раздела + кнопка возврата в меню.
// Возвращает массив рядов вида {text, url} или {text, data}.
export function keyboardFor(sectionId) {
  if (sectionId === "start") {
    return [
      ...MENU.map((row) => row.map((b) => ({ text: b.text, data: b.id }))),
      [{ text: "Сайт проекта", url: LINKS.site }],
    ];
  }
  const section = SECTIONS[sectionId];
  return [...(section.buttons || []), [{ text: "« В меню", data: "start" }]];
}
